export function messageFor(message, language) {
  if (!message || /^\s*ru(?:[-_,;\s]|$)/i.test(language || "")) return message;
  if (EN[message]) return EN[message];
  let m;
  if ((m = /^Слишком длинный текст \(максимум (\d+)\)$/.exec(message))) return `Text is too long (maximum ${m[1]} characters)`;
  if ((m = /^В опросе от (\d+) до (\d+) вариантов$/.exec(message))) return `A poll must have ${m[1]}–${m[2]} options`;
  if ((m = /^Вариант длиннее (\d+) символов$/.exec(message))) return `A poll option exceeds ${m[1]} characters`;
  if ((m = /^Не больше (\d+) кодов — удали ненужные$/.exec(message))) return `Maximum ${m[1]} codes; delete unused codes`;
  // Never leak an untranslated Russian system message into the default English UI.
  return /[А-Яа-яЁё]/.test(message) ? "Something went wrong. Please try again." : message;
}
