W, H, S = 240, 80, 4
BG, FG, GRAY, ACC, SH = (0,0,0), (214,214,214), (138,138,138), (255,255,85), (46,46,46)
img = Image.new("RGB", (W, H), BG); d = ImageDraw.Draw(img)
def text(s, x, y, c, k=1):
    for ch in s:
        for r, row in enumerate(F[ch]):
            for col, b in enumerate(row):
                if b == "1": d.rectangle([x + col*k, y + r*k, x + col*k + k - 1, y + r*k + k - 1], fill=c)
        x += 6 * k
def width(s, k=1): return len(s) * 6 * k - k
def center(s, y, c, k=1, shadow=None):
    x = (W - width(s, k)) // 2
    if shadow: text(s, x + k, y + k, shadow, k)
    text(s, x, y, c, k)
# panel with offset shadow, like the in-game RetroUi boxes
d.rectangle([9, 9, W - 6, H - 6], fill=SH)
d.rectangle([6, 6, W - 9, H - 9], fill=BG, outline=GRAY)
center("FEED_", 17, ACC, 3, SH)
center("MINEFEED + RETROCONSOLE", 46, FG)
center("MODS BY GAIGEN", 58, GRAY)
for y in range(0, H, 2):  # scanlines
    for xx in range(W):
        p = img.getpixel((xx, y)); img.putpixel((xx, y), tuple(int(v * 0.82) for v in p))
img.resize((W * S, H * S), Image.NEAREST).save("/data/discord/banner.png")
